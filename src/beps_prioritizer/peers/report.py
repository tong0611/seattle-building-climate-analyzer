"""Validation of the peer gap (ENERGY STAR agreement, persistence) and the report.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from beps_prioritizer.peers.crossfit import N_FOLDS, TARGETS, log_metrics
from beps_prioritizer.peers.models import MODELS, PRODUCTION_MODEL
from beps_prioritizer.reporting import md_table

ES_CHECK_TYPES = ["Office", "Multifamily Housing", "K-12 School", "Hotel",
                  "Non-Refrigerated Warehouse", "Retail Store"]


def validation_table(df: pd.DataFrame, details: dict) -> pd.DataFrame:
    """Does the EUI gap look like real performance? Two checks per model.

    - Agreement with EPA's ENERGY STAR score (an independent, peer-relative 1-100
      rating; higher = better, so a good gap measure correlates negatively).
    - Persistence: correlation of a building's gap in consecutive years. Model noise
      would not persist; a real performance gap should.
    """
    ok = details["train_ok"]
    es = df["energy_star_score"]
    has_es = ok & es.notna()
    rows = []
    for name in MODELS:
        resid = np.log(df[TARGETS["eui"]]) - np.log(details["preds"][("eui", name)])
        within = [
            resid[has_es & (df["use1_type"] == t)].corr(
                es[has_es & (df["use1_type"] == t)], method="spearman")
            for t in ES_CHECK_TYPES
        ]
        panel = df.loc[ok, ["building_id", "data_year"]].assign(r=resid[ok])
        panel = panel.sort_values(["building_id", "data_year"])
        panel["r_next"] = panel.groupby("building_id")["r"].shift(-1)
        rows.append({
            "model": name,
            "spearman_vs_energy_star": resid[has_es].corr(es[has_es], method="spearman"),
            "spearman_vs_energy_star_within_type": float(np.mean(within)),
            "gap_persistence_next_year": panel[["r", "r_next"]].dropna().corr().iloc[0, 1],
        })
    return pd.DataFrame(rows).set_index("model").round(3)


def error_by_building_type(df: pd.DataFrame, details: dict) -> pd.DataFrame:
    """Production-model typical error, per city building type."""
    ok = details["train_ok"]
    rows = []
    for bt, idx in df[ok].groupby("building_type", observed=True).groups.items():
        row = {"building_type": bt}
        for short, target in TARGETS.items():
            m = log_metrics(df.loc[idx, target], details["preds"][(short, PRODUCTION_MODEL)][idx])
            row["rows"] = m["rows"]
            row[f"{short}_typical_error_pct"] = round(m["typical_error_pct"], 1)
        rows.append(row)
    return pd.DataFrame(rows).set_index("building_type").sort_values("rows", ascending=False)


def top_gaps(df: pd.DataFrame, out: pd.DataFrame, q: pd.DataFrame, k: int = 15) -> pd.DataFrame:
    """Largest EUI gaps vs peers in the latest year, high-trust records only."""
    latest = df["data_year"] == df["data_year"].max()
    m = latest & (q["trust_tier"] == "high") & out["eui_ratio"].notna()
    t = df.loc[m, ["building_name", "use1_type", "gfa_buildings", "site_eui_wn"]].assign(
        expected_eui=out.loc[m, "expected_site_eui_wn"].round(1),
        eui_ratio=out.loc[m, "eui_ratio"].round(2),
        ghg_ratio=out.loc[m, "ghg_ratio"].round(2),
    )
    # Rank by excess energy (kBtu above expected), so large buildings are not drowned out
    # by small ones with extreme ratios.
    excess = (t["site_eui_wn"] - t["expected_eui"]) * t["gfa_buildings"]
    return t.assign(excess_mmbtu=(excess / 1000).round(0)).nlargest(k, "excess_mmbtu")


def build_report(df: pd.DataFrame, q: pd.DataFrame, out: pd.DataFrame, details: dict) -> str:
    metrics = details["metrics"].copy()
    metrics[["mae_log", "typical_error_pct", "r2_log"]] = metrics[
        ["mae_log", "typical_error_pct", "r2_log"]].round(3)
    return "\n".join([
        "# Peer model: expected energy and emissions intensity",
        "",
        "_Generated by `beps-peer`. Gaps are estimates and mean \"worth a look\"._",
        "",
        "## Setup",
        "",
        "- Targets: weather-normalized site EUI (kBtu/sf) and GHG intensity (kgCO2e/sf), "
        "modeled on the log scale.",
        f"- Training rows: {int(details['train_ok'].sum()):,} building-years with no critical "
        "data-quality flag.",
        f"- Validation: {N_FOLDS}-fold GroupKFold **by building**; every row is predicted by a "
        "model that never saw that building in any year.",
        "- Features: floor-area share by use type, size, parking ratio, floors, number of "
        "buildings, building type, data year. No fuel mix and no building age (both are "
        "levers, not peer traits).",
        "",
        "## Accuracy on held-out buildings",
        "",
        "`typical_error_pct` = median absolute error expressed as a percentage. Remaining "
        "error is expected: what the model cannot explain from physical characteristics "
        "(operations, equipment, fuel choice) is the performance gap this tool looks for.",
        "",
        md_table(metrics, index=False),
        "",
        "## Does the gap measure real performance?",
        "",
        "- **ENERGY STAR agreement:** Spearman correlation of the EUI gap with EPA's "
        "ENERGY STAR score (negative = agrees). ENERGY STAR also adjusts for operating "
        "hours, workers, and other inputs not in this dataset, so perfect agreement is "
        "not expected.",
        "- **Persistence:** correlation of a building's gap with its gap the next year. "
        "Noise would not persist.",
        "",
        md_table(validation_table(df, details)),
        "",
        "## What drives the expected EUI (grouped permutation importance)",
        "",
        "Increase in log-MAE when a feature group is shuffled, on one held-out fold.",
        "",
        md_table(details["importance"].round(3).rename("mae_log_increase").to_frame()),
        "",
        "## Production model error by building type",
        "",
        md_table(error_by_building_type(df, details)),
        "",
        f"## Largest excess energy vs peers, {int(df['data_year'].max())} (high-trust records)",
        "",
        "`eui_ratio` = actual / expected. `excess_mmbtu` = energy above the peer "
        "expectation, in million Btu per year.",
        "",
        md_table(top_gaps(df, out, q), index=False),
        "",
    ])
